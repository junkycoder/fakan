# Diary CLI
# 
# Usage:
#   diary Tvoje, klidně i česká, poznámka do deníčku.
#   # or
#   diary -add "Tvoje, klidně i česká, poznámka do deníčku."
#   Commands:
#   -add <entry>     default command to add a new diary entry
#   -list            List all diary entries
#   -delete <id>     Delete a diary entry by ID
#   -search <keyword> Search diary entries by keyword
#   Options:
#   -h, --help      Show this help message and exit 
#   -v, --version   Show version information and exit
#   Example:
#   diary Today I went to the park and had a great time!
#   diary -list, -l
#   diary -delete, d 1
#   diary -search, -s "park"
